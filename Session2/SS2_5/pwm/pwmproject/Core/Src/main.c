void Blink_Update(PwmBlinkChannel *ch)
{
    // Giá trị CCR đúng theo % duty riêng của từng kênh (ARR = 999 -> mẫu số 1000)
    // 25%  -> ccrOn = 250
    // 50%  -> ccrOn = 500
    // 75%  -> ccrOn = 750
    // 100% -> ccrOn = 1000 (lớn hơn ARR -> luôn HIGH tuyệt đối)
    uint32_t ccrOn = (PWM_ARR_STEPS * (uint32_t)ch->duty_percent) / 100;

    if (ch->duty_percent == 0)
    {
        __HAL_TIM_SET_COMPARE(&htim1, ch->channel, 0); // luôn tắt
        return;
    }

    // Tất cả các kênh, kể cả 100%, đều nháy ON/OFF theo thời gian riêng.
    // Duty càng cao thì thời gian ON càng dài, thời gian OFF càng ngắn.
    // Ép tối thiểu offTime (MIN_OFF_TIME_MS) để mắt thường vẫn thấy rõ chớp tắt,
    // kể cả với kênh duty 100%.
    uint32_t onTime  = (BASE_PERIOD_MS * ch->duty_percent) / 100;
    uint32_t offTime = BASE_PERIOD_MS - onTime;
    if (offTime < MIN_OFF_TIME_MS) offTime = MIN_OFF_TIME_MS;
    uint32_t now = HAL_GetTick();

    if (ch->state == 1) // đang ON
    {
        if (now - ch->lastToggle >= onTime)
        {
            __HAL_TIM_SET_COMPARE(&htim1, ch->channel, 0); // tắt
            ch->state = 0;
            ch->lastToggle = now;
        }
    }
    else // đang OFF
    {
        if (now - ch->lastToggle >= offTime)
        {
            // Bật đúng mức CCR riêng của kênh này (KHÔNG dùng chung 999 cho mọi kênh)
            __HAL_TIM_SET_COMPARE(&htim1, ch->channel, ccrOn);
            ch->state = 1;
            ch->lastToggle = now;
        }
    }
}
